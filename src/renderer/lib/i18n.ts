const dicts = { en, ru, zh, es };
export type Lang = keyof typeof dicts;
export type LangPref = Lang | 'system';

/** Language names in their own language, for the settings menu. */
export const LANG_NAMES: Record<Lang, string> = { ru: 'Русский', en: 'English', zh: '中文', es: 'Español' };

export function detectLang(): Lang {
  const l = (navigator.languages?.[0] ?? navigator.language ?? 'en').toLowerCase();
  if (/^(ru|uk|be|kk)/.test(l)) return 'ru';
  if (l.startsWith('zh')) return 'zh';
  if (l.startsWith('es')) return 'es';
  return 'en';
}

